#!/usr/bin/env python3
"""TDG laboratory: does the cubic S4 sign twist repair the physical GR bridge?

All group tests are exact to floating-point precision; they use the canonical J
ray under the explicit cubic embedding, not a recovered microscopic TDG-Q chart.
No changes to TDG's canonical files or to the Born/GR claims.
"""
from __future__ import annotations
import itertools
import json
from pathlib import Path
import numpy as np
from numpy.linalg import matrix_rank, norm, eigvalsh, svd

OUT = Path('/mnt/data/tdg_q_twist_no_go_results_2026_11_06.json')
E = np.array([
    np.diag([1., -1., 0.]) / np.sqrt(2.),
    np.diag([1., 1., -2.]) / np.sqrt(6.),
    np.array([[0, 1, 0], [1, 0, 0], [0, 0, 0]]) / np.sqrt(2.),
    np.array([[0, 0, 1], [0, 0, 0], [1, 0, 0]]) / np.sqrt(2.),
    np.array([[0, 0, 0], [0, 0, 1], [0, 1, 0]]) / np.sqrt(2.)
])
assert norm(np.einsum('aij,bij->ab', E, E)-np.eye(5)) < 1e-12
J = np.zeros((3, 5))
J[0, 4] = J[1, 3] = J[2, 2] = -1 / np.sqrt(3)

def U5(R):
    return np.einsum('aij,bij->ab', E,
                     np.einsum('ij,bjk,lk->bil', R, E, R))

def sign_character(R):
    # For proper signed permutation matrices only. NOT the spatial determinant.
    axes = np.argmax(np.abs(R), axis=0)
    P = np.eye(3)[:, axes]
    return int(round(np.linalg.det(P)))

rotations = []
for perm in itertools.permutations(range(3)):
    for signs in itertools.product((-1., 1.), repeat=3):
        R = np.eye(3)[:, perm] @ np.diag(signs)
        if round(np.linalg.det(R)) == 1:
            rotations.append(R)
assert len(rotations) == 24

# Genuine discrete character and exact twisted S4 intertwiner.
max_character_error = 0
max_J_error = 0
for R in rotations:
    max_J_error = max(max_J_error, norm(R @ J @ U5(R).T - sign_character(R) * J))
    for S in rotations:
        max_character_error = max(max_character_error,
            abs(sign_character(R @ S)-sign_character(R)*sign_character(S)))
assert max_character_error == 0
assert max_J_error < 2e-14

# Rank of all linear intertwiners T : V_twisted -> V_standard.
# Equivariance R T = T (chi(R) R). Matrix F-order vec(T):
# (I kron R - (chi R)^T kron I) vec_F(T) = 0.
I = np.eye(3)
rows = []
for R in rotations:
    X = sign_character(R)*R
    rows.append(np.kron(I, R) - np.kron(X.T, I))
A = np.vstack(rows)
svals = svd(A, compute_uv=False)
rank_intertwine = matrix_rank(A, tol=1e-10)
assert rank_intertwine == 9, (rank_intertwine, svals)

# On any finite connected graph, links from local node frames are Z2-flat.
site_rotations = [rotations[i] for i in [0, 5, 12, 19]]
edge_signs = []
for a in range(4):
    b = (a+1) % 4
    edge_signs.append(sign_character(site_rotations[a].T@site_rotations[b]))
flat_loop = int(np.prod(edge_signs))
assert flat_loop == 1
# A single frustrated edge changes the Wilson product; gauge transformations
# s_a -> +/- s_a preserve the loop product.
frustrated = edge_signs.copy()
frustrated[-1] *= -1
nonflat_loop = int(np.prod(frustrated))
assert nonflat_loop == -1
for gauge in itertools.product((-1, 1), repeat=4):
    altered = [frustrated[a]*gauge[a]*gauge[(a+1)%4] for a in range(4)]
    assert int(np.prod(altered)) == -1

# A constant twist cannot manufacture a physical derivative:
# physical TT for k=(0,0,1) is generated by plus and cross.
plus = np.diag([1., -1., 0.]) / np.sqrt(2.)
cross = E[2]
k = np.array([0.,0.,1.])
def coeff(H):
    return np.einsum('aij,ij->a', E, H)
TT = np.column_stack([coeff(plus), coeff(cross)])
Dk = np.einsum('aij,j->ia', E, k)
assert norm(Dk@TT) < 1e-14
assert norm(J@TT) > 0.5
Jtt=J@TT
Jtt_gram=Jtt.T@Jtt
assert norm(Jtt_gram-np.diag([0., 1./3.])) < 1e-14

# Integrate out an auxiliary vector with a strictly positive mass m:
# M_eff = k^2 I - (c^2/m^2) J^T J.
# It induces a physical birefringence between TT plus/cross in this toy model.
c=1.
m=5.
M_eff=np.eye(5)-(c*c/m/m)*J.T@J
M_eff_TT=TT.T@M_eff@TT
split=float(np.ptp(eigvalsh(M_eff_TT)))
assert abs(split-1/(3*m*m)) < 1e-13
covariant_M_eff_TT=TT.T@(np.eye(5)-(c*c/m/m)*Dk.T@Dk)@TT
assert norm(covariant_M_eff_TT-np.eye(2))<1e-14

# Twist classification alone does not cure covariance under general SO(3).
R90=np.array([[0.,-1.,0.],[1.,0.,0.],[0.,0.,1.]])
R60=np.array([[0.5,-np.sqrt(3)/2,0],[np.sqrt(3)/2,0.5,0],[0,0,1.]])
quarter_turn_defect=norm(R90@J@U5(R90).T-J)
generic_turn_defect=norm(R60@J@U5(R60).T-J)
assert quarter_turn_defect > 1.9
assert generic_turn_defect > 0.1
# Crucial: sign character is not continuous on SO3 as an independent
# representation; connected SO3 has no nontrivial continuous map to {+/-1}.

result={
    'status':'Exact finite S4/cubic representation diagnosis; not a TDG Q-derived GR bridge',
    'max_character_homomorphism_error':max_character_error,
    'max_twisted_intertwiner_error':max_J_error,
    'hom_space_3twist_to_3_dimension':9-rank_intertwine,
    'intertwiner_constraint_rank':rank_intertwine,
    'min_singular_value_intertwiner_constraints':float(svals[-1]),
    'four_node_loop_flat_Z2_holonomy':flat_loop,
    'four_node_loop_frustrated_Z2_holonomy':nonflat_loop,
    'TT_J_gram_plus_cross':Jtt_gram.tolist(),
    'TT_canonical_divergence_norm':float(norm(Dk@TT)),
    'auxiliary_vector_mass':m,
    'auxiliary_mixing_c':c,
    'toy_effective_TT_eigenvalues':eigvalsh(M_eff_TT).tolist(),
    'toy_effective_TT_split':split,
    'covariant_divergence_TT_eigenvalues':eigvalsh(covariant_M_eff_TT).tolist(),
    'quarter_turn_standard_covariance_defect':float(quarter_turn_defect),
    'generic_sixty_degree_covariance_defect':float(generic_turn_defect),
    'no_go':'Only an S4 sign twist is insufficient to produce a continuous SO3 vector or eliminate physical TT birefringence.',
    'open':'Needs a Q-generated directional derivative/transport and a first-class nonlinear constraint structure.'
}
OUT.write_text(json.dumps(result,indent=2,ensure_ascii=False,default=lambda x: x.item()),encoding='utf-8')
print(json.dumps(result,ensure_ascii=False,indent=2,default=lambda x: x.item()))
