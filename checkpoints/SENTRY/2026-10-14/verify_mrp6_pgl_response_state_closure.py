import math, numpy as np
from numpy.linalg import det, matrix_rank, norm

q=np.array([[1/math.sqrt(2),1/math.sqrt(6)],
            [-1/math.sqrt(2),1/math.sqrt(6)],
            [0,-2/math.sqrt(6)]],float)
def G(d): return q.T@np.diag(np.asarray(d,float))@q
def P(d):
    g=G(d)
    return g/math.sqrt(det(g))

eps=1e-7
def tangent(v):
    return (P(np.exp(eps*np.asarray(v)))-P(np.exp(-eps*np.asarray(v))))/(2*eps)

X=tangent([1,-1,0])
Y=tangent([1,1,-2])
J=X@Y-Y@X
L=np.column_stack([X.reshape(-1),Y.reshape(-1),J.reshape(-1)])
assert matrix_rank(L,tol=1e-8)==3
assert norm(X-X.T)<1e-8
assert norm(Y-Y.T)<1e-8
assert norm(J+J.T)<1e-8

pinv=np.linalg.pinv(L)
for A,B in [(J,X),(J,Y),(X,Y)]:
    K=A@B-B@A
    rec=(L@(pinv@K.reshape(-1))).reshape(2,2)
    assert norm(K-rec)<1e-7

rng=np.random.default_rng(606)
for _ in range(500):
    d1=np.exp(rng.normal(size=3)); d2=np.exp(rng.normal(size=3)); d3=np.exp(rng.normal(size=3))
    th=rng.normal()
    O=np.array([[math.cos(th),-math.sin(th)],[math.sin(th),math.cos(th)]])
    A=P(d1)@O; B=P(d2); C=P(d3)
    T=(C@B)@A
    assert norm((C@B)@A-C@(B@A))<1e-11
    assert norm(T@np.linalg.inv(T)-np.eye(2))<1e-10
    c=math.exp(rng.normal())
    assert norm(P(c*d1)-P(d1))<1e-11

